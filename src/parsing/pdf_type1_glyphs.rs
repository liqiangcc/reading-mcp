//! Glyph name to Unicode text for the Type 1 fonts this corpus embeds (PDF-6b).
//!
//! The table is the Adobe Glyph List restricted to the blocks a Type 1 program
//! in the corpus and the TeX fixture names: Basic Latin through Latin
//! Extended-A, Spacing Modifier Letters, Greek, and General Punctuation
//! through Miscellaneous Technical (U+2000-U+23FF), plus the handful of
//! geometric and music names Computer Modern uses.  It is transcribed from the
//! same list as lopdf 0.44's `src/encodings/glyphnames.rs`, which is where the
//! names and code points come from; the names the list lacks or spells for a
//! different glyph in TeX are overridden in `pdf_type1_builtin.rs`.
//!
//! The list is sorted by name so the lookup is a binary search.

/// The Unicode text for an Adobe Glyph List name.
pub(super) fn glyph_name_unicode(name: &[u8]) -> Option<&'static str> {
    GLYPH_NAMES
        .binary_search_by(|(key, _)| (*key).cmp(name))
        .ok()
        .map(|index| GLYPH_NAMES[index].1)
}

